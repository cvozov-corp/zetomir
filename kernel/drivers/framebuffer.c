static void pixel(i32 x, i32 y, u32 c) {
    if (!ready || x < 0 || y < 0 || (u64)x >= fb_width || (u64)y >= fb_height) return;
    volatile u32 *row = (volatile u32 *)((volatile u8 *)pixels + (u64)y * fb_pitch);
    row[x] = c;
}
void fb_init(void *address, u64 width, u64 height, u64 pitch, u16 bpp) {
    if (!address || !width || !height || bpp != 32) return;
    pixels = (volatile u32 *)address;
    fb_width = width; fb_height = height; fb_pitch = pitch; ready = 1;
}
int fb_ready(void) { return ready; }
void fb_clear(u32 color) {
    if (!ready) return;
    for (u64 y=0; y<fb_height; ++y)
        for (u64 x=0; x<fb_width; ++x) pixel((i32)x,(i32)y,color);
}
void fb_rect(i32 x, i32 y, i32 w, i32 h, u32 color) {
    for (i32 yy=0; yy<h; ++yy)
        for (i32 xx=0; xx<w; ++xx) pixel(x+xx,y+yy,color);
}
static int glyph_index(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 'a' + 'A');
    if (c >= 'A' && c <= 'Z') return c-'A';
    if (c >= '0' && c <= '9') return 26+c-'0';
    return -1;
}
static void draw_char(i32 x, i32 y, char c, u32 color, i32 scale) {
    if (c == ' ') return;
    int idx = glyph_index(c);
    if (idx < 0) {
        if (c == '-' || c == '_' || c == ':' || c == '.' || c == '/' || c == '>') {
            u8 bits = c == '-' ? 0x08 : (c == '_' ? 0x40 : (c == ':' ? 0x14 : (c == '.' ? 0x40 : 0x01)));
            for (int col=0; col<5; ++col) if (bits & (1u<<col))
                for (int yy=0; yy<scale; ++yy) for (int xx=0; xx<scale; ++xx)
                    pixel(x+col*scale+xx,y+5*scale+yy,color);
        }
        return;
    }
    for (int col=0; col<5; ++col)
        for (int row=0; row<7; ++row)
            if (font[idx][col] & (1u<<row))
                for (int yy=0; yy<scale; ++yy)
                    for (int xx=0; xx<scale; ++xx)
                        pixel(x+col*scale+xx,y+row*scale+yy,color);
}
void fb_text(i32 x, i32 y, const char *s, u32 color, i32 scale) {
    if (scale < 1) scale=1;
    while (*s) {
        if (*s == '\n') { y += 9*scale; x=8; }
        else { draw_char(x,y,*s,color,scale); x += 6*scale; }
        ++s;
    }
}
